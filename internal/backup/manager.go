package backup

import (
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"
)

type Manager struct{}

// PruneConanBackups keeps the newest retention backup files and removes older
// ones. It never considers the active game database a retention candidate.
func (Manager) PruneConanBackups(root string, keep int) (int, error) {
	if root == "" {
		return 0, fmt.Errorf("backup root is required")
	}
	if keep < 1 {
		return 0, fmt.Errorf("backup retention must be at least 1")
	}
	type candidate struct {
		path string
		when time.Time
	}
	var candidates []candidate
	if err := filepath.WalkDir(root, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !isConanBackup(entry.Name()) {
			return nil
		}
		info, err := entry.Info()
		if err != nil {
			return err
		}
		candidates = append(candidates, candidate{path: path, when: info.ModTime()})
		return nil
	}); err != nil {
		if os.IsNotExist(err) {
			return 0, nil
		}
		return 0, fmt.Errorf("scan backups for retention: %w", err)
	}
	sort.SliceStable(candidates, func(i, j int) bool {
		return candidates[i].when.After(candidates[j].when)
	})
	removed := 0
	for _, item := range candidates[keep:] {
		if err := os.Remove(item.path); err != nil {
			return removed, fmt.Errorf("remove expired backup %s: %w", item.path, err)
		}
		removed++
	}
	return removed, nil
}

func (Manager) PrepareRamdisk(path string) error {
	if path == "" {
		return fmt.Errorf("ramdisk path is empty")
	}
	return os.MkdirAll(path, 0o750)
}

// CopyConanBackups copies only backup-like files generated by Conan. It intentionally
// does not copy game.db or another active database file while the server is running.
func (Manager) CopyConanBackups(source, destination string) (int, error) {
	if source == "" || destination == "" {
		return 0, fmt.Errorf("backup source and destination are required")
	}
	if err := os.MkdirAll(destination, 0o750); err != nil {
		return 0, fmt.Errorf("create backup destination: %w", err)
	}
	count := 0
	err := filepath.WalkDir(source, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			return nil
		}
		if !isConanBackup(entry.Name()) {
			return nil
		}
		relative, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		target := filepath.Join(destination, relative)
		if err := copyFile(path, target); err != nil {
			return err
		}
		count++
		return nil
	})
	if err != nil {
		return count, fmt.Errorf("copy Conan backups: %w", err)
	}
	return count, nil
}

func isConanBackup(name string) bool {
	lower := strings.ToLower(name)
	if lower == "game.db" || !strings.Contains(lower, "backup") {
		return false
	}
	return strings.HasSuffix(lower, ".db") || strings.HasSuffix(lower, ".bak") || strings.HasSuffix(lower, ".backup")
}

func copyFile(source, target string) error {
	if err := os.MkdirAll(filepath.Dir(target), 0o750); err != nil {
		return err
	}
	input, err := os.Open(source)
	if err != nil {
		return err
	}
	defer input.Close()
	temporary := target + fmt.Sprintf(".tmp-%d", time.Now().UnixNano())
	output, err := os.OpenFile(temporary, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o640)
	if err != nil {
		return err
	}
	if _, err = io.Copy(output, input); err != nil {
		output.Close()
		_ = os.Remove(temporary)
		return err
	}
	if err = output.Sync(); err != nil {
		output.Close()
		_ = os.Remove(temporary)
		return err
	}
	if err = output.Close(); err != nil {
		_ = os.Remove(temporary)
		return err
	}
	return os.Rename(temporary, target)
}
